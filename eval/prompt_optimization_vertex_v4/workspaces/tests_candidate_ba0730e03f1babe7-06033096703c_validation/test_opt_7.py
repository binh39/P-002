import pytest
from isort import parse, wrap
from isort.output import _with_from_imports
from isort.settings import Config


def test_with_from_imports_full_coverage():
    # Helper to construct valid ParsedContent NamedTuple
    def make_parsed(
        imports=None,
        as_map=None,
        categorized_comments=None,
        trailing_commas=None,
    ):
        return parse.ParsedContent(
            in_lines=[],
            lines_without_imports=[],
            import_index=0,
            place_imports={},
            import_placements={},
            as_map=as_map or {"from": {}},
            imports=imports or {"STDLIB": {"from": {}}},
            categorized_comments=categorized_comments or {
                "from": {},
                "above": {"from": {}},
                "nested": {},
                "straight": {},
            },
            change_count=0,
            original_line_count=0,
            line_separator="\n",
            sections=None,
            verbose_output=[],
            trailing_commas=trailing_commas or set(),
        )

    config = Config(
        line_length=10,
        combine_star=True,
        combine_as_imports=True,
        multi_line_output=wrap.Modes.HANGING_INDENT,
    )

    # 1. Test mod_skip in remove_imports
    parsed_skip = make_parsed()
    res = _with_from_imports(
        parsed_skip,
        config,
        ["mod_skip"],
        "STDLIB",
        remove_imports=["mod_skip"],
        import_type="import",
    )
    assert res == []

    # --- Test 2: combine_star and above_comments ---
    parsed_star = make_parsed(
        imports={"STDLIB": {"from": {"mod_star": {"*": True}}}},
        categorized_comments={
            "from": {"mod_star": ()},
            "above": {"from": {"mod_star": ["# above star"]}},
            "nested": {"mod_star": {"*": "star nest"}},
            "straight": {},
        },
    )
    res_star = _with_from_imports(
        parsed_star, config, ["mod_star"], "STDLIB", remove_imports=[], import_type="import"
    )
    assert any("# above star" in line for line in res_star)

    # --- Test 3: force_single_line with comments and as_imports ---
    config_single = Config(
        line_length=40,
        force_single_line=True,
        single_line_exclusions=["mod_excl"],
        comment_prefix="#",
    )
    parsed_single = make_parsed(
        imports={"STDLIB": {"from": {"mod_single": {"a": True}}}},
        as_map={"from": {"mod_single.a": ["a_as"]}},
        categorized_comments={
            "from": {"mod_single": ("# comment 1",)},
            "above": {"from": {}},
            "nested": {"mod_single": {"a": "nest a"}},
            "straight": {"mod_single.a": ["straight a"]},
        },
    )
    res_single = _with_from_imports(
        parsed_single, config_single, ["mod_single"], "STDLIB", remove_imports=[], import_type="import"
    )
    assert len(res_single) > 0

    # --- Test 4: noqa with HANGING_INDENT ---
    config_noqa = Config(
        line_length=10,
        multi_line_output=wrap.Modes.HANGING_INDENT,
        comment_prefix="#",
    )
    parsed_noqa = make_parsed(
        imports={"STDLIB": {"from": {"mod_noqa": {"d": True}}}},
        categorized_comments={
            "from": {"mod_noqa": ("# base comment",)},
            "above": {"from": {}},
            "nested": {"mod_noqa": {"d": "noqa: comment"}},
            "straight": {},
        },
    )
    res_noqa = _with_from_imports(
        parsed_noqa, config_noqa, ["mod_noqa"], "STDLIB", remove_imports=[], import_type="import"
    )
    assert len(res_noqa) > 0

    # --- Test 5: split_on_trailing_comma ---
    config_comma = Config(
        line_length=5,
        split_on_trailing_comma=True,
        comment_prefix="#",
    )
    parsed_comma = make_parsed(
        imports={"STDLIB": {"from": {"mod_comma": {"h": True, "i": True}}}},
        trailing_commas={"mod_comma"},
    )
    res_comma = _with_from_imports(
        parsed_comma, config_comma, ["mod_comma"], "STDLIB", remove_imports=[], import_type="import"
    )
    assert len(res_comma) > 0

    # --- Test 6: GRID multi_line_output falling back to VERTICAL_GRID (lines 547-563) ---
    config_grid = Config(
        line_length=10,
        multi_line_output=wrap.Modes.GRID,
        comment_prefix="#",
    )
    parsed_grid = make_parsed(
        imports={"STDLIB": {"from": {"mod_grid": {"e": True, "f": True, "g": True}}}},
    )
