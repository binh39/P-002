from collections import defaultdict
from isort import parse, wrap
from isort.output import _with_from_imports
from isort.settings import Config


def test_with_from_imports_full_coverage():
    # Construct a ParsedContent object via parse.ParsedContent factory or positional/keyword init,
    # ensuring trailing_commas is correctly passed during instantiation if it's a frozen dataclass or similar.
    parsed = parse.ParsedContent(
        in_lines=(),
        lines_without_imports=(),
        import_index=0,
        place_imports=False,
        import_placements={},
        as_map=defaultdict(dict),
        imports=defaultdict(dict),
        categorized_comments=defaultdict(dict),
        change_count=0,
        original_line_count=0,
        sections=(),
        verbose_output=False,
        trailing_commas={"mod_as"},
        line_separator="\n",
    )

    # Populate parsed structures used by _with_from_imports
    section = "THIRDPARTY"
    parsed.imports[section]["from"] = defaultdict(dict)
    
    remove_imports = ["mod_remove.A"]

    parsed.imports[section]["from"]["mod_remove"] = {"A": True}

    parsed.imports[section]["from"]["mod_star"] = {"*": True, "B": True}
    parsed.as_map["from"] = {}

    parsed.categorized_comments["from"] = {
        "mod_star": ["# star comment"],
        "mod_as": ["# from comment"],
        "mod_force_single": ["# single comment"],
    }
    parsed.categorized_comments["above"] = {
        "from": {
            "mod_star": ["# above star"],
        }
    }
    parsed.categorized_comments["nested"] = {
        "mod_star": {},
        "mod_as": {
            "B": "# nested B",
            "noqa_imp": "# noqa: E501",
        },
        "mod_force_single": {
            "X": "# nested X",
        },
    }
    parsed.categorized_comments["straight"] = {}

    # Setup mod_as imports and as_map
    parsed.imports[section]["from"]["mod_as"] = {
        "A": True,
        "B": True,
        "noqa_imp": True,
        "C": True,
        "D": True,
    }
    parsed.as_map["from"]["mod_as.A"] = ["AliasA"]
    parsed.as_map["from"]["mod_as.C"] = ["AliasC"]

    config = Config(
        no_inline_sort=False,
        force_single_line=False,
        only_sections=False,
        reverse_sort=False,
        combine_as_imports=True,
        combine_star=True,
        ignore_comments=False,
        comment_prefix="#",
        force_grid_wrap=2,
        line_length=10,
        multi_line_output=wrap.Modes.VERTICAL,
        split_on_trailing_comma=True,
    )

    from_modules = ["mod_remove", "mod_star", "mod_as"]
    
    output1 = _with_from_imports(
        parsed=parsed,
        config=config,
        from_modules=from_modules,
        section=section,
        remove_imports=remove_imports,
        import_type="import",
    )
    assert isinstance(output1, list)

