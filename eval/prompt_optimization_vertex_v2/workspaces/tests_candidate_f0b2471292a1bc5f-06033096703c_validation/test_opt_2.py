class DummyParsed:
    def __init__(self):
        self.imports = defaultdict(lambda: {"from": defaultdict(lambda: defaultdict(bool))})
        self.as_map = {"from": defaultdict(list)}
        self.categorized_comments = {
            "from": defaultdict(list),
            "above": {"from": defaultdict(list)},
            "nested": defaultdict(dict),
            "straight": defaultdict(list),
        }
        self.trailing_commas = set()
        self.line_separator = "\n"


def test_with_from_imports_full_coverage():
    # Test case 1: remove_imports filtering and branch 518->525 condition triggered
    # Line 257: module in remove_imports -> continue
    # Branch 518->525: len(import_statement) > config.line_length, len(from_import_section) > 0,
    # config.multi_line_output NOT in (wrap.Modes.GRID, wrap.Modes.VERTICAL) (e.g. HANGING_INDENT)
    parsed = DummyParsed()
    parsed.imports["DEFAULT"]["from"]["modA"]["item1"] = True
    parsed.imports["DEFAULT"]["from"]["modA"]["item2"] = True
    config = Config(
        line_length=10,
        multi_line_output=wrap.Modes.HANGING_INDENT,
        combine_as_imports=False,
    )
    res = _with_from_imports(
        parsed=parsed,
        config=config,
        from_modules=["modToRemove", "modA"],
        section="DEFAULT",
        remove_imports=["modToRemove", "modA.itemToRemove"],
        import_type="import",
    )
    assert isinstance(res, list)

